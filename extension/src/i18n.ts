const ALL: Record<Lang, Strings> = { en, es, ru, pt, it };

export function pickLang(lang: Lang | null): Lang {
  if (lang) return lang;
  const nav = navigator.language.slice(0, 2) as Lang;
  return nav in ALL ? nav : 'en';
}

export function strings(lang: Lang): Strings {
  return ALL[lang];
}
